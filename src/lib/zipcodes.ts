/**
 * Validates if the given zipcode is within Maryland.
 * Uses the mdZipcodes mapping or general MD ZIP range (20588, 20600-21999).
 */
export function isMarylandZipcode(zip: string): boolean {
  if (mdZipcodes[zip]) return true;
  
  const numZip = parseInt(zip, 10);
  return !isNaN(numZip) && ((numZip >= 20588 && numZip <= 20588) || (numZip >= 20600 && numZip <= 21999));
}
